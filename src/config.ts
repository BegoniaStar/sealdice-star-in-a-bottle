export const fallbackDefaults = {
  unknownUser: '未知用户',
  unknownQq: '未知QQ号',
} as const;

export function registerPluginConfigs(extension: seal.ExtInfo): void {
  seal.ext.registerTemplateConfig(
    extension,
    'starStyles',
    [...defaultStarStyles],
    '跳入星海时随机抽取的星星样式；可填写多条候选值。',
    '星海',
  );
  for (const [key, value] of Object.entries(commandHelpDefaults))
    seal.ext.registerStringConfig(
      extension,
      `commandHelp.${key}`,
      value,
      '对应指令在 SealDice 帮助中的说明。',
      '指令',
    );
  seal.ext.registerStringConfig(
    extension,
    'fallback.unknownUser',
    fallbackDefaults.unknownUser,
    '消息中没有可用昵称时显示的投放者名称。',
    '星海',
  );
  seal.ext.registerStringConfig(
    extension,
    'fallback.unknownQq',
    fallbackDefaults.unknownQq,
    '消息中没有可用 QQ 号时保存的投放者标识。',
    '星海',
  );
}

export function readStarStyles(extension: seal.ExtInfo): string[] {
  const configured = seal.ext
    .getTemplateConfig(extension, 'starStyles')
    .map((item) => item.trim())
    .filter((item) => item !== '');
  return configured.length > 0 ? configured : [...defaultStarStyles];
}

export function readCommandHelp(
  extension: seal.ExtInfo,
  key: keyof typeof commandHelpDefaults,
): string {
  const value = seal.ext
    .getStringConfig(extension, `commandHelp.${key}`)
    .trim();
  return value || commandHelpDefaults[key];
}

export function readFallback(
  extension: seal.ExtInfo,
  key: keyof typeof fallbackDefaults,
): string {
  const value = seal.ext.getStringConfig(extension, `fallback.${key}`).trim();
  return value || fallbackDefaults[key];
}
